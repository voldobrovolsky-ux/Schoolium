// Симуляция онбординга первой школы: нагрузка на модератора (L-16) и цена
// нового элемента (L-10). Замер, не инвариант.
const CFG = { classes: 8, students: 15, teachers: 10, subjectsPerClass: 6, groupsSubjects: 1 };
let taps = 0, screens = 0;
const step = (t, s, label) => { taps += t; screens += s; };

step(5, 2, 'мастер классов: параллели, «без литер», численность, группы, пол');
step(CFG.classes * CFG.students * (2 + 3), CFG.classes, 'профили: тап по профилю + 3 поля (Ф, И, О-опц)');
step(CFG.classes * CFG.subjectsPerClass * 3, 1, 'предметы: карточка × (название, класс, сохранить)');
step(CFG.teachers * 4, 1, 'активация персонала: открыть карточку, QR, (сотрудник вводит своё), закрыть');
step(CFG.classes * CFG.subjectsPerClass * 3, 0, 'привязка: открыть карточку, «+», выбор класса/групп');
step(8 + CFG.teachers * 2 + 3 + 5, 4, 'модалка: четверти(8 дат) + нагрузка + приоритеты + параметры дня');
step(2, 1, 'генерация + подтверждение');

const SEC_PER_TAP = 4;
const minutes = Math.round(taps * SEC_PER_TAP / 60);
console.log(`Онбординг первой школы (${CFG.classes} классов × ${CFG.students}):`);
console.log(`  касаний модератора: ${taps}, экранов: ${screens}, оценка времени: ~${minutes} мин (${SEC_PER_TAP} с/касание)`);
console.log(`  из них ввод контингента: ${CFG.classes*CFG.students*5} касаний (${Math.round(CFG.classes*CFG.students*5*SEC_PER_TAP/60)} мин) — доминирует`);
console.log('');
console.log('Зонд L-10 «цена нового элемента»:');
console.log('  добавить 9-й класс: мастер не нужен — карточка класса + 15 профилей + привязки ≈ 100 касаний [3 точки: контингент, предметы, нагрузка]');
console.log('  добавить ученика в класс: 1 кнопка + 3 поля + авто-сортировка + авто-группа ≈ 5 касаний [1 точка]');
console.log('  добавить предмет классу: карточка + QR-привязка + часы + РЕГЕНЕРАЦИЯ всей сетки [4 точки — регенерация делает добавление предмета среди года дорогим: слот на инкрементальную правку сетки]');
if (minutes > 90) { console.error('❌ порог L-16 (полный онбординг ≤ 90 мин) превышен'); process.exit(1); }
console.log(`✅ порог L-16: ~${minutes} мин ≤ 90 мин на полный онбординг силами одного человека.`);
