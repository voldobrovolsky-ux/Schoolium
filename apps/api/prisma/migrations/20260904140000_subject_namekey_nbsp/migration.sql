-- Пакет 1.5.0, добор к AR-201: ключ имени предмета считается ОДИНАКОВО в базе и в коде.
--
-- Бэкфилл миграции 20260904090000 обрезал края через `btrim` и схлопывал `\s+`:
-- в Postgres класс `\s` не включает неразрывный пробел (U+00A0), а `btrim` без
-- второго аргумента снимает только обычный пробел — табуляцию и перевод строки
-- по краям он оставлял. `subjectNameKey` в коде (JS `trim`/`\s`) снимает и то, и
-- другое, поэтому у имени с неразрывным пробелом ключи расходились, и дубль
-- «Алгебра» против «Алгебра» (с U+00A0) не находился ни поиском дублей, ни
-- проверкой при создании карточки.
--
-- Только расширение: колонок не добавляет и не удаляет, пересчитывает значение.
UPDATE "SchoolSubject"
SET "nameKey" = replace(
      lower(
        regexp_replace(
          regexp_replace(replace("name", U&'\00A0', ' '), '^\s+|\s+$', '', 'g'),
          '\s+', ' ', 'g'
        )
      ),
      'ё', 'е'
    );
